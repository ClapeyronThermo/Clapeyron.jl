@inline function ∂ζeff╱∂ζ_X(λ, ζ_X)
    A    = SAFTVRMieconsts.A
    λ⁻¹  = one(λ)/λ
    # ζeff = A·(1·ζ + λ⁻¹·ζ² + λ⁻²·ζ³ + λ⁻³·ζ⁴)
    return A * evalpoly(ζ_X, (one(λ), 2λ⁻¹, 3λ⁻¹*λ⁻¹, 4λ⁻¹*λ⁻¹*λ⁻¹))
end



